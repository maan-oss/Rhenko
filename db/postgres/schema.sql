  update posts set views_count = views_count - 1 where id = old.post_id and author_id <> old.viewer_id;
  return old;
end $$;
create trigger views_count after insert or delete on post_views for each row execute function rhenko_views_count();

-- A post counts toward its author's posts when it is a top-level post or a thread part, published, not a draft, not removed.
create or replace function rhenko_post_counted(reply text, thread text, draft bigint, publish bigint, removed bigint) returns boolean
  language sql immutable as $$
  select (reply is null or thread is not null) and draft = 0 and publish is null and removed is null
$$;

create or replace function rhenko_posts_authored() returns trigger language plpgsql as $$
begin
  if tg_op = 'INSERT' then
    if rhenko_post_counted(new.reply_to_id, new.thread_id, new.is_draft, new.publish_at, new.removed_at) then
      update users set posts_count = posts_count + 1 where id = new.author_id;
    end if;
    return new;
  elsif tg_op = 'DELETE' then
    if rhenko_post_counted(old.reply_to_id, old.thread_id, old.is_draft, old.publish_at, old.removed_at) then
      update users set posts_count = posts_count - 1 where id = old.author_id;
    end if;
    return old;
  end if;
  if rhenko_post_counted(old.reply_to_id, old.thread_id, old.is_draft, old.publish_at, old.removed_at)
     is distinct from rhenko_post_counted(new.reply_to_id, new.thread_id, new.is_draft, new.publish_at, new.removed_at) then
    update users set posts_count = posts_count
      + (case when rhenko_post_counted(new.reply_to_id, new.thread_id, new.is_draft, new.publish_at, new.removed_at) then 1 else -1 end)
      where id = new.author_id;
  end if;
  return new;
end $$;
create trigger posts_authored after insert or delete on posts for each row execute function rhenko_posts_authored();
create trigger posts_authored_state after update of is_draft, publish_at, removed_at, reply_to_id, thread_id on posts
  for each row execute function rhenko_posts_authored();

-- A published post that is not a draft counts toward its parent's replies and its quoted post's quotes.
create or replace function rhenko_posts_replies() returns trigger language plpgsql as $$
begin
  if tg_op = 'INSERT' then
    if new.is_draft = 0 and new.publish_at is null then
      update posts set replies_count = replies_count + 1 where id = new.reply_to_id;
      update posts set quotes_count = quotes_count + 1 where id = new.quote_of_id;
    end if;
    return new;
  elsif tg_op = 'DELETE' then
    if old.is_draft = 0 and old.publish_at is null then
      update posts set replies_count = replies_count - 1 where id = old.reply_to_id;
      update posts set quotes_count = quotes_count - 1 where id = old.quote_of_id;
    end if;
    return old;
  end if;
  if (old.is_draft = 0 and old.publish_at is null) is distinct from (new.is_draft = 0 and new.publish_at is null) then
    update posts set replies_count = replies_count + (case when new.is_draft = 0 and new.publish_at is null then 1 else -1 end)
      where id = new.reply_to_id;
    update posts set quotes_count = quotes_count + (case when new.is_draft = 0 and new.publish_at is null then 1 else -1 end)
      where id = new.quote_of_id;
  end if;
  return new;
end $$;
create trigger posts_replies after insert or delete on posts for each row execute function rhenko_posts_replies();
create trigger posts_replies_live after update of is_draft, publish_at on posts for each row execute function rhenko_posts_replies();

-- Search. The SQLite build used an FTS5 trigram index; a trigram GIN index gives the same substring matching in Postgres.
create index posts_body_trigram on posts using gin (body gin_trgm_ops);

-- The event bus. Each server process listens on this channel and reads new events as they are written, instead of
-- checking the table on a timer. The payload is empty: a listener reads the events table itself.
create or replace function rhenko_notify_event() returns trigger language plpgsql as $$
begin
  perform pg_notify('rhenko_events', '');
  return null;
end $$;
drop trigger if exists events_notify on events;
create trigger events_notify after insert on events for each row execute function rhenko_notify_event();

