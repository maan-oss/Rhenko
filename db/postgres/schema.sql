-- Counters kept by triggers. Each function mirrors one of the triggers in the SQLite schema.

create or replace function rhenko_follows_counts() returns trigger language plpgsql as $$
begin
  if tg_op = 'INSERT' then
    update users set followers_count = followers_count + 1 where id = new.followee_id;
    update users set following_count = following_count + 1 where id = new.follower_id;
    return new;
  end if;
  update users set followers_count = followers_count - 1 where id = old.followee_id;
  update users set following_count = following_count - 1 where id = old.follower_id;
  return old;
end $$;
create trigger follows_counts after insert or delete on follows for each row execute function rhenko_follows_counts();

